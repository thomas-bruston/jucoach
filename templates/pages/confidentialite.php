    <h1>POLITIQUE DE CONFIDENTIALITÉ</h1>

    <p>Dernière mise à jour : 11 septembre 2026</p>

    <p>Ju Coach Sportif attache une grande importance à la protection de vos données personnelles.
    Cette page explique quelles données sont collectées sur ce site, pourquoi, pendant combien de temps,
    et comment vous pouvez exercer vos droits.</p>

    <h3>1. Responsable du traitement</h3>
    <p>Le responsable du traitement des données collectées sur ce site est <strong>Ju Coach Sportif</strong>
    (SARLU), dont le siège social est à Nosy Be, Madagascar, représenté par Julien Fachan. Pour toute
    question relative à vos données personnelles, vous pouvez contacter
    <a href="mailto:jucoaching@outlook.com">jucoaching@outlook.com</a> ou utiliser le
    <a href="/contact">formulaire de contact</a>. Voir aussi les <a href="/mentions-legales">mentions légales</a>.</p>

    <h3>2. Données collectées</h3>

    <h4>Création de compte</h4>
    <ul>
        <li>Nom, prénom, adresse e-mail, mot de passe (stocké de façon chiffrée, jamais en clair)</li>
        <li>Téléphone, adresse postale (facultative)</li>
    </ul>

    <h4>Questionnaire sportif</h4>
    <p>Pour vous proposer un programme réellement adapté, le questionnaire recueille des informations
    détaillées sur votre profil physique et vos objectifs : âge, genre, taille, poids, condition physique,
    habitudes alimentaires, qualité de sommeil, niveau de stress — ainsi que, le cas échéant,
    <strong>des informations relatives à votre santé</strong> (blessures, douleurs, problèmes de santé,
    allergies). Ces données de santé sont une catégorie de données particulièrement protégée par la
    réglementation : elles ne sont collectées qu'avec votre <strong>consentement explicite</strong>,
    donné lors de l'envoi du questionnaire, et ne sont utilisées que pour l'élaboration de votre
    programme personnalisé.</p>

    <h4>Commandes</h4>
    <p>Lorsque vous choisissez un programme, sont enregistrés : le programme sélectionné, son prix et la
    date. Aucune donnée bancaire n'est collectée ni stockée sur ce site : le paiement s'effectue
    directement avec Julien, en dehors du site.</p>

    <h4>Formulaire de contact</h4>
    <p>Nom, adresse e-mail et contenu du message que vous envoyez.</p>

    <h3>3. Pourquoi ces données sont collectées (finalités et base légale)</h3>
    <ul>
        <li><strong>Exécution du contrat</strong> : création et gestion de votre compte, suivi de vos programmes choisis, réponse à vos demandes.</li>
        <li><strong>Consentement explicite</strong> : traitement des données de santé du questionnaire, utilisées exclusivement pour construire votre programme de coaching.</li>
        <li><strong>Intérêt légitime</strong> : traitement des messages envoyés via le formulaire de contact.</li>
    </ul>

    <h3>4. Destinataires des données</h3>
    <p>Vos données ne sont ni vendues, ni louées, ni partagées avec des tiers à des fins commerciales.
    Elles sont accessibles uniquement par Julien (administrateur du site) et, dans la stricte mesure du
    nécessaire au fonctionnement technique du site, par l'hébergeur (Hostinger) et le service d'envoi
    d'e-mails utilisé pour les notifications (confirmation de compte, réinitialisation de mot de passe,
    confirmation de commande).</p>

    <h3>5. Durée de conservation</h3>
    <p>Les données liées à votre compte (identité, questionnaire, commandes) sont conservées tant que
    votre compte est actif. Les données issues d'une simple prise de contact (formulaire de contact, sans
    création de compte) sont conservées 3 ans après le dernier échange. Vous pouvez à tout moment demander
    la suppression de vos données (voir « Vos droits » ci-dessous). Les liens de réinitialisation de mot
    de passe expirent automatiquement après 1 heure et ne sont utilisables qu'une seule fois.</p>

    <h3>6. Cookies</h3>
    <p>Ce site utilise uniquement un cookie de session, strictement nécessaire à votre connexion
    (maintien de votre session et sécurité — protection contre la falsification de requêtes). Il ne
    s'agit pas d'un cookie de mesure d'audience ou de publicité, et il ne nécessite donc pas de
    consentement préalable. Ce site n'utilise aucun outil de suivi publicitaire ni d'analytics tiers.</p>
    <p>Certaines ressources techniques (polices de caractères, icônes) sont chargées depuis des serveurs
    tiers (Google Fonts, Cloudflare) pour l'affichage des pages, ce qui implique une connexion technique
    à ces serveurs lors du chargement du site.</p>

    <h3>7. Vos droits</h3>
    <p>Conformément au Règlement Général sur la Protection des Données (RGPD), vous disposez des droits
    suivants sur vos données personnelles :</p>
    <ul>
        <li><strong>Droit d'accès et de rectification</strong> : consultez et modifiez vos informations à tout moment depuis « Mon profil ».</li>
        <li><strong>Droit à l'effacement</strong> : vous pouvez supprimer définitivement votre compte et l'ensemble de vos données depuis « Mon profil » (section « Supprimer mon compte »), ou en en faisant la demande via le <a href="/contact">formulaire de contact</a>.</li>
        <li><strong>Droit d'opposition et de retrait du consentement</strong> : vous pouvez à tout moment vous opposer au traitement de vos données ou retirer votre consentement, notamment concernant les données de santé du questionnaire.</li>
        <li><strong>Droit à la portabilité</strong> : vous pouvez demander une copie de vos données dans un format structuré.</li>
    </ul>
    <p>Pour exercer ces droits, contactez <a href="mailto:jucoaching@outlook.com">jucoaching@outlook.com</a>.
    Une réponse vous sera apportée dans un délai raisonnable, et au plus tard un mois après réception de
    votre demande. Si vous estimez que vos droits ne sont pas respectés, vous pouvez introduire une
    réclamation auprès de l'autorité de protection des données compétente (en France, la CNIL —
    www.cnil.fr).</p>

    <h3>8. Sécurité</h3>
    <p>Des mesures techniques sont mises en place pour protéger vos données : mots de passe chiffrés,
    connexion sécurisée, accès restreint aux seules personnes autorisées. Aucun système n'étant
    infaillible à 100 %, nous vous invitons à choisir un mot de passe robuste et à ne le communiquer à
    personne.</p>
</div>

